const BD_DIVISIONS = Object.keys(BD_LOCATIONS);

function getDistrictsForDivision(division) {
  return division && BD_LOCATIONS[division] ? Object.keys(BD_LOCATIONS[division]) : [];
}

function getUpazilasForDistrict(division, district) {
  return (division && district && BD_LOCATIONS[division] && BD_LOCATIONS[division][district])
    ? BD_LOCATIONS[division][district] : [];
}

// কোন জেলা কোন বিভাগে তা দ্রুত খুঁজে বের করার জন্য
function findDivisionForDistrict(district) {
  for (const div of BD_DIVISIONS) {
    if (BD_LOCATIONS[div][district]) return div;
  }
  return null;
}

