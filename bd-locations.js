// রি-ইউজেবল বিভাগ/জেলা/উপজেলা ড্রপডাউন HTML
// idPrefix দিয়ে একই পেজে একাধিক ফর্মে আলাদা আলাদা id ব্যবহার করা যাবে
// ============================================
function locationDropdownsHTML(idPrefix, defaults={}) {
  const divisionId = `${idPrefix}Division`;
  const districtId = `${idPrefix}District`;
  const upazilaId = `${idPrefix}Upazila`;
  const upazilaTextId = `${idPrefix}UpazilaText`;
  return `
    <div class="input-group"><label>বিভাগ *</label>
      <select id="${divisionId}" onchange="onDivisionChange('${idPrefix}')">
        <option value="">সিলেক্ট করুন</option>
        ${BD_DIVISIONS.map(d=>`<option value="${d}" ${defaults.division===d?'selected':''}>${d}</option>`).join('')}
      </select></div>
    <div class="input-group"><label>জেলা *</label>
      <select id="${districtId}" onchange="onDistrictChange('${idPrefix}')">
        <option value="">আগে বিভাগ সিলেক্ট করুন</option>
      </select></div>
    <div class="input-group"><label>উপজেলা *</label>
      <select id="${upazilaId}" onchange="onUpazilaSelectChange('${idPrefix}')">
        <option value="">আগে জেলা সিলেক্ট করুন</option>
      </select>
      <input type="text" id="${upazilaTextId}" placeholder="তালিকায় না থাকলে এখানে টাইপ করুন" value="${defaults.upazila||''}" style="margin-top:6px;">
    </div>
  `;
}

function onDivisionChange(idPrefix) {
  const division = document.getElementById(`${idPrefix}Division`).value;
  const districtSelect = document.getElementById(`${idPrefix}District`);
  const districts = getDistrictsForDivision(division);
  districtSelect.innerHTML = `<option value="">সিলেক্ট করুন</option>` + districts.map(d=>`<option value="${d}">${d}</option>`).join('');
  document.getElementById(`${idPrefix}Upazila`).innerHTML = `<option value="">আগে জেলা সিলেক্ট করুন</option>`;
}

function onDistrictChange(idPrefix) {
  const division = document.getElementById(`${idPrefix}Division`).value;
  const district = document.getElementById(`${idPrefix}District`).value;
  const upazilaSelect = document.getElementById(`${idPrefix}Upazila`);
  const upazilas = getUpazilasForDistrict(division, district);
  upazilaSelect.innerHTML = `<option value="">সিলেক্ট করুন</option>` + upazilas.map(u=>`<option value="${u}">${u}</option>`).join('') + `<option value="">➕ তালিকায় নেই — নিচে টাইপ করুন</option>`;
}

function onUpazilaSelectChange(idPrefix) {
  const select = document.getElementById(`${idPrefix}Upazila`);
  const textInput = document.getElementById(`${idPrefix}UpazilaText`);
  if (select.value) textInput.value = select.value; // সিলেক্ট করলে টেক্সট বক্সেও বসে যাবে, এডিট করা যাবে
}

// ফর্ম থেকে চূড়ান্ত জেলা/উপজেলা মান বের করার হেল্পার
function getLocationValues(idPrefix) {
  const district = document.getElementById(`${idPrefix}District`)?.value || '';
  const upazilaText = document.getElementById(`${idPrefix}UpazilaText`)?.value?.trim() || '';
  const upazilaSelect = document.getElementById(`${idPrefix}Upazila`)?.value || '';
  return { district, upazila: upazilaText || upazilaSelect };
}

// বিভাগ/জেলা প্রি-সিলেক্ট করে দেওয়ার জন্য (এডিট ফর্মের জন্য দরকার হলে)
function preselectLocation(idPrefix, division, district) {
  const divisionSelect = document.getElementById(`${idPrefix}Division`);
  if (divisionSelect && division) {
    divisionSelect.value = division;
    onDivisionChange(idPrefix);
    const districtSelect = document.getElementById(`${idPrefix}District`);
    if (districtSelect && district) {
      districtSelect.value = district;
      onDistrictChange(idPrefix);
    }
  }
}
